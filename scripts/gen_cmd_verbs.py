"""dll/cmd_verbs.h: the pipe's commands (the verbs control.c's execute() knows), for the scripts' command functions
(expr.c x_command_verb: spawn(...), stats(...) ...). Run by dll/build.sh; the header is kept in git for a build
without Python."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DLL = os.path.join(os.path.dirname(HERE), 'dll')


def main():
    src = open(os.path.join(DLL, 'control.c'), encoding='utf-8', errors='replace').read()
    a = src.index('static void execute(const char *cmd, char *out) {')
    b = src.index('\n}\n', a)
    verbs = sorted(set(re.findall(r'!strcmp\(verb, "([a-z_0-9]+)"\)', src[a:b])))
    out = ['// generated by scripts/gen_cmd_verbs.py from control.c execute() - do not edit',
           '// the pipe commands a script may call as functions (expr.c x_command_verb)',
           'static const char *const k_cmd_verbs[] = {']
    line = '   '
    for v in verbs:
        item = ' "%s",' % v
        if len(line) + len(item) > 116:
            out.append(line)
            line = '   '
        line += item
    out.append(line)
    out.append('};')
    text = '\n'.join(out) + '\n'
    path = os.path.join(DLL, 'cmd_verbs.h')
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
    if old != text:
        open(path, 'w', encoding='utf-8', newline='\n').write(text)
        print('cmd_verbs.h: %d commands' % len(verbs))


if __name__ == '__main__':
    main()
