"""The object types' identifiers: docs/units.md (every type by epoch: id, identifier, English name, kind, stats, cost)
and dll/unit_names.h (the identifiers for the DLL, by type id; the kinds - the game's families - and each type's).

An identifier is the type's internal name from the game's data (dbobjects.dat - the same in every game language),
lowercase, every run of other characters one '_': "b  Guard Tower - Bronze" -> b_guard_tower_bronze. One rule, no
shortening (some short forms would clash: "Gun Siege04 Catapult" and "x Catapult - ME"); unique, checked here.
The English names: the community DB editor's language.txt (dat_read.fetch: scripts/dats/, downloaded). Run after the data changes:
    python scripts/gen_units.py
"""
import collections
import os
import re

import dat_read

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
EPOCHS = ['Prehistoric', 'Stone Age', 'Copper Age', 'Bronze Age', 'Dark Age', 'Middle Ages', 'Renaissance',
          'Imperial Age', 'Industrial Age', 'Atomic Age - World War I', 'Atomic Age - World War II',
          'Atomic Age - Modern', 'Digital Age', 'Nano Age', 'Space Age']
BUILDINGS = ('Building', 'Towers', 'Walls', 'AA Building')


def families(db):   # {family id: name} from the data converter's log (Family[3] = Building)
    out = {}
    for ln in open(os.path.join(db, 'converteroutput.log'), encoding='latin-1'):
        m = re.match(r'Family\[(\d+)\] = (.*)', ln.strip())
        if m:
            out[int(m.group(1))] = m.group(2).strip()
    return out


def ident(name):
    return re.sub(r'[^a-z0-9]+', '_', name.lower()).strip('_')


def num(x, nd=1):
    if not x:
        return ''
    s = ('%.' + str(nd) + 'f') % x
    return s.rstrip('0').rstrip('.') if '.' in s else s


def main():
    dat_read.fetch()
    db = os.path.join(ROOT, 'data', 'db')
    objs = [r for r in dat_read.read(os.path.join(db, 'dbobjects.dat'), 'dbobjects') if r['ID'] >= 0 and r['Name']]
    techs = dat_read.read(os.path.join(db, 'dbtechtree.dat'), 'dbtechtree', adjust=1,
                          extra_count_field='Num of tech builders')
    lang = dat_read.language(os.path.join(HERE, 'dats', 'language.txt'))
    fam = families(db)
    kinds = {i: ident(n) for i, n in fam.items()}   # kind.<identifier> in the texts
    if len(set(kinds.values())) != len(kinds):
        raise SystemExit('kind identifiers used twice: %s' % kinds)
    if max(kinds) >= 255:
        raise SystemExit('more kinds than an unsigned char holds')

    names = {}
    for r in objs:
        names.setdefault(ident(r['Name']), []).append(r['ID'])
    clash = {k: v for k, v in names.items() if len(v) > 1}
    if clash:
        raise SystemExit('identifiers used twice: %s' % clash)
    made = collections.defaultdict(list)   # the tech that makes it (a type can have several: the earliest counts)
    for t in techs:
        if t['Object ID'] >= 0 and t['Is object?'] & 1:
            made[t['Object ID']].append(t)

    top = max(r['ID'] for r in objs) + 1
    by_id = {r['ID']: r for r in objs}
    with open(os.path.join(ROOT, 'dll', 'unit_names.h'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// generated by scripts/gen_units.py from the game data (dbobjects.dat) - do not edit\n')
        f.write('// the object types\' identifiers by type id (docs/units.md): the internal name, lowercase, other characters "_"\n')
        f.write('#define UNIT_TYPES %d\n' % top)
        f.write('static const char *const k_unit_ident[UNIT_TYPES] = {\n')
        for i in range(top):
            r = by_id.get(i)
            f.write('    %s,%s\n' % ('"%s"' % ident(r['Name']) if r else 'NULL', '   // %d' % i if i % 10 == 0 else ''))
        f.write('};\n')
        f.write('// the kinds: the game\'s families (the armour and bonus class, "Family ID") as identifiers - kind.towers\n')
        f.write('#define UNIT_KINDS %d\n' % (max(kinds) + 1))
        f.write('static const char *const k_kind_ident[UNIT_KINDS] = {\n')
        line = '   '
        for i in range(max(kinds) + 1):
            item = ' "%s",' % kinds[i] if i in kinds else ' NULL,'
            if len(line) + len(item) > 118: f.write(line + '\n'); line = '   '
            line += item
        f.write(line + '\n};\n')
        f.write('// each type\'s kind (k_kind_ident), by type id; 255: no type\n')
        f.write('static const unsigned char k_unit_kind[UNIT_TYPES] = {\n')
        for i in range(0, top, 24):
            f.write('    %s,\n' % ', '.join(str(by_id[j]['Family ID'] if j in by_id else 255) for j in range(i, min(i + 24, top))))
        f.write('};\n')

    rows = collections.defaultdict(list)
    other = []
    for r in objs:
        ts = made.get(r['ID'])
        disp = lang.get(r['Language ID'], '')
        kind = fam.get(r['Family ID'], '')
        building = r['Is building?'] or kind in BUILDINGS
        kind = kinds.get(r['Family ID'], '')
        if not ts:
            other.append((ident(r['Name']), r['ID'], disp, kind, r['Health']))
            continue
        t = min(ts, key=lambda t: (t['Starting epoch'], t['ID']))
        end = max(x['Ending epoch'] for x in ts)
        cost = '/'.join(str(t[k]) for k in ('Food cost', 'Wood cost', 'Stone cost', 'Gold cost', 'Iron cost'))
        rows[t['Starting epoch']].append((0 if building else 1, ident(r['Name']), r['ID'], disp, kind,
                                          '%d-%d' % (t['Starting epoch'], end), r['Health'], r['Attack'],
                                          num(r['Max range']), num(r['Line of sight']), num(r['Speed'], 2),
                                          r['Population count'] or '', cost, num(t['Build time'] / 1000.0)))

    out = []
    w = out.append
    w('# Object types')
    w('')
    w('Generated by `scripts/gen_units.py` from the game data - do not edit. Every unit and building type with its id,')
    w('its **identifier** and its English name. The identifier is the type\'s internal name in the game data, the same in')
    w('every game language: lowercase, every run of other characters one `_` (`b  Guard Tower - Bronze` ->')
    w('`b_guard_tower_bronze`). The prefixes are the designers\': `b` building, `a` aircraft, `inf`/`arch`/`cav` + the')
    w('epoch infantry, archers, cavalry, `gun` siege and guns, `x` special variants, `amb` animals, `res` resources.')
    w('')
    w('Kind is the game\'s family of the type (its armour and bonus class) - in the texts `kind.<kind>`: `me.count(kind.towers)`')
    w('counts every tower whatever its epoch, `unit.<identifier>` only that type (config/aimod_ai/README.md). Buildings')
    w('come first in each epoch.')
    w('')
    w('| kind | the game\'s name | types |')
    w('|---|---|---|')
    n_kind = collections.Counter(r['Family ID'] for r in objs)
    for i in sorted(kinds):
        w('| `%s` | %s | %d |' % (kinds[i], fam[i], n_kind.get(i, 0)))
    w('')
    w('The stats are the base values from the data, before upgrades and civilization bonuses: hit points, attack,')
    w('range and line of sight in tiles, speed, population, cost food/wood/stone/gold/iron and build time in seconds.')
    w('Epochs are numbered as in the mod\'s logs (0 = Prehistoric); "epochs" is from when to when the game offers it.')
    w('')
    for e in sorted(rows):
        w('## %d %s' % (e, EPOCHS[e] if 0 <= e < len(EPOCHS) else '?'))
        w('')
        w('| id | identifier | name | kind | epochs | HP | attack | range | sight | speed | pop | cost F/W/S/G/I | time |')
        w('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
        for x in sorted(rows[e]):
            w('| %d | `%s` | %s | `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % ((x[2], x[1]) + x[3:]))
        w('')
    w('## Not built in a game')
    w('')
    w('Types no technology makes: animals, trees, resources, projectiles, debris, scenario-only and unused objects.')
    w('')
    w('| id | identifier | name | kind | HP |')
    w('|---|---|---|---|---|')
    for x in sorted(other):
        w('| %d | `%s` | %s | `%s` | %s |' % (x[1], x[0], x[2], x[3], x[4] or ''))
    w('')
    with open(os.path.join(ROOT, 'docs', 'units.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print('%d types (%d built, %d other), ids 0..%d' % (len(objs), len(objs) - len(other), len(other), top - 1))


if __name__ == '__main__':
    main()
