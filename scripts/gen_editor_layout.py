# Build dll/game/api/raw/editor_layout.h from layout_diff.py output: the scenario editor's 1024x768 layout values that
# EE-AOC.exe uses, as patches for Empire Earth.exe (imm32 operands, or float constants to redirect), each with how
# it follows the screen size, so the mod can compute the layout for any resolution:
#   value(W, H) = AoC value + fx/2 * (W - 1024) + fy/2 * (H - 768)
# fx/fy (0, 1 or 2 halves) come from the EE -> AoC change: +224 (= 1024 - 800) follows the width (anchored right or
# stretching), +168 (= 768 - 600) the height, half of that = centred. ANCHOR gives them for AoC's redesigns.
# usage: python gen_editor_layout.py aoc/work/editor_layout3.tsv aoc/work/editor_layout_pages2.tsv dll/game/api/raw/editor_layout.h
import sys, struct

PUSH_DELTAS = {168, 224, 112, 84}
# constructor 0x58D3E1: minimap rectangle (AoC builds it from constants elsewhere, so the diff can't pair it)
MANUAL = [(0x58D5AC, 662.0, 854.16), (0x58D5B3, 795.0, 1023.0), (0x58D5BA, 454.0, 598.16), (0x58D5C1, 587.0, 767.0)]

# operands to leave alone although they pass the filter
EXCLUDE = {
    # UIFullBackground("textures\Scenfull", 4, 3, .., 800, 600): not the screen size but the size the tiles cover -
    # the engine scales them by screen / this. EE's tiles are 200 px (AoC's 256 px, hence its 1024x768), so the
    # original values stretch the art to any resolution
    0x58E58C, 0x58E591,
    0x561100, 0x561130, 0x561160,   # EESEInstructions: assert line numbers
    0x5630DC, 0x563148, 0x563176,   # window message ids (WM_USER + n)
}
# entries whose EE -> AoC change isn't a plain move: (fx, fy) in halves
ANCHOR = {
    0x58D5AC: (2, 0), 0x58D5B3: (2, 0), 0x58D5BA: (0, 2), 0x58D5C1: (0, 2),   # minimap: bigger in AoC, bottom right
    0x58DA04: (2, 0), 0x58DA0B: (2, 0), 0x58DA12: (0, 2), 0x58DA19: (0, 2),   # hide-UI checkbox, next to the minimap
}

def factors(addr, old, new):
    if addr in ANCHOR:
        return ANCHOR[addr]
    hits = [(fx, fy) for fx in (0, 1, 2) for fy in (0, 1, 2) if abs(fx * 112 + fy * 84 - (new - old)) < 0.6]
    if len(hits) != 1:
        sys.exit('no unique size rule for %06X (%g -> %g): add it to ANCHOR' % (addr, old, new))
    return hits[0]

# our own corrections to AoC's values: operand address -> value
OVERRIDE = {
    # trigger "hide UI" checkbox (19x19, constructor 0x58D3E1): AoC moves it right by 224 like the panels, but the
    # minimap's left edge only moves 192 (662 -> 854), so it ends up half hidden - 19 px left, above the exit button
    0x58DA04: 830.0, 0x58DA0B: 849.0,
}

def u32f(f):
    return struct.unpack('<I', struct.pack('<f', f))[0]

rows, seen = [], set(EXCLUDE)
for line in (l for f in sys.argv[1:-1] for l in open(f)):
    kind, func, name, insn, opaddr, vk, old, new, text = line.rstrip('\n').split('\t')
    old, new, opaddr = float(old), float(new), int(opaddr, 16)
    mnem = text.split()[0]
    if opaddr in seen:
        continue
    keep = False
    if kind == 'imm' and vk == 'f' and mnem == 'mov' and max(abs(old), abs(new)) <= 1100:
        keep = True
    elif kind == 'const' and vk == 'f':
        keep = True
    elif kind == 'imm' and vk == 'i' and mnem == 'push' and old >= 250 and round(new - old) in PUSH_DELTAS:
        keep = True   # (assert line numbers moved by 3-4 lines in AoC's sources; the deltas exclude them)
    if keep:
        seen.add(opaddr)
        new = OVERRIDE.get(opaddr, new)
        rows.append((kind, opaddr, vk, old, new, name, text))
for addr, old, new in MANUAL:
    if addr not in seen:
        rows.append(('imm', addr, 'f', old, new, 'FUN_0058d3e1 (minimap)', 'manual'))

with open(sys.argv[-1], 'w') as out:
    out.write('// Generated by scripts/gen_editor_layout.py from scripts/layout_diff.py - do not edit.\n'
              '// Scenario editor layout: the values Art of Conquest uses at 1024x768, patched into Empire Earth.exe, and\n'
              '// how each follows the screen size: value = aoc + fx/2 * (W - 1024) + fy/2 * (H - 768).\n'
              '// kind 0: imm32 operand at addr (old = EE value, checked); kind 1: float constant read through the\n'
              '// absolute operand at addr - the operand is redirected to a float of our own. isf: float, else int.\n'
              'internal const struct { uint32_t addr; uint8_t kind, isf; uint32_t old; float aoc; int8_t fx, fy; } k_editor_layout[] = {\n')
    for kind, addr, vk, old, new, name, text in sorted(rows, key=lambda r: r[1]):
        isf = kind == 'const' or vk == 'f'
        o = u32f(old) if isf else int(old)   # the original value (checked before patching)
        fx, fy = factors(addr, old, new)
        out.write('    { 0x%06X, %d, %d, 0x%08X, %.2ff, %d, %d },   // %s: %s  %g -> %g\n'
                  % (addr, 1 if kind == 'const' else 0, int(isf), o, new, fx, fy, name, text, old, new))
    out.write('};\n')
print(len(rows), 'patches written to', sys.argv[-1])
