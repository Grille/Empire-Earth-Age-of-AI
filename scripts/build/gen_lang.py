"""The language's objects made C (run by dll/build.sh): dll/game_script/lang.h from lang/*.cs (lang_read.py) - the tables
relations.c includes. k_xmembers: a player's members (player.cs) - name, kind (XM_: a value, a player, a relation, a
method, an effect), doc, type, arguments, set (a script may), mine (a text has it alone); k_xglobals: the names a text
has of its own (names.cs); k_xk_player / k_xk_game / k_xk_slot: each kind's members as the check reads them
(script/host.h x_kmember). A type is host.h's code: the language's own XT_..., a kind relations.c's XK_..., T? with
X_NULLABLE, T[] with X_LIST_OF."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lang_read   # noqa: E402

OUT = os.path.join(lang_read.ROOT, 'dll', 'game_script', 'lang.h')
KINDS = ('player', 'game', 'slot', 'unit')   # relations.c's XK_ order: k_xk_<kind> each
OWN = {'int': 'XT_INT', 'float': 'XT_FLOAT', 'bool': 'XT_BOOL', 'text': 'XT_TEXT', 'vec2': 'XT_VEC2', 'vec3': 'XT_VEC3',
       'vec4': 'XT_VEC4', 'epoch': 'XT_EPOCH', 'color': 'XT_COLOR', 'unit_type': 'XT_UTYPE', 'function': 'XT_FN',
       'record': 'XT_REC', 'trigger': 'XT_TRIG', 'player': 'XK_PLAYER', 'game': 'XK_GAME', 'slot': 'XK_SLOT', 'unit': 'XK_UNIT',
       'void': 'X_ANY', 'any': 'X_ANY', 'filter': 'X_ANY'}


def ctype(t, where):
    nullable = t.endswith('?')
    t = t.rstrip('?')
    lst = t.endswith('[]')
    t = t[:-2] if lst else t
    if t not in OWN:
        raise SystemExit('%s: an unknown type %s (lang/language.cs: the language\'s types)' % (where, t))
    c = OWN[t]
    if c == 'X_ANY':
        return c
    return ('X_LIST_OF + ' if lst else '') + c + (' | X_NULLABLE' if nullable else '')


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    kinds = lang_read.read_all()
    out = ['// GENERATED by scripts/build/gen_lang.py from lang/*.cs (the language\'s objects) - not edited by hand. What each',
           '// table is: gen_lang.py\'s header; the declarations\' format: lang/language.cs.',
           'enum { XM_PLAYER, XM_LINK, XM_REL, XM_FILTER, XM_DO };   // a value, a player (them.lord), A.<relation>(B), '
           'A.count(filter), an effect',
           'struct xmember { const char *name; int kind; const char *doc; short type; signed char amin, amax, set, mine; };']

    def xmembers(cname, kind):
        out.append('internal const struct xmember %s[] = {' % cname)
        for m in kind.members:
            lo, hi = m.arity
            xk = lang_read.xm_kind(m) if kind.name == 'player' else 'XM_REL' if m.has('with_them') else 'XM_PLAYER'   # a name: a value
            out.append('    { %s, %s, %s, %s, %d, %d, %d, %d },' % (cstr(m.name), xk, cstr(m.doc),
                                                                 ctype(m.type, m.where), lo, hi, m.has('set'), m.has('mine')))
        out.append('};')

    def kmembers(cname, kind):
        out.append('internal const struct x_kmember %s[] = {' % cname)
        for m in kind.members:
            lo, hi = m.arity
            out.append('    { %s, %d, %d, %s, %d },' % (cstr(m.name), lo, hi, ctype(m.type, m.where), m.has('set')))
        out.append('};')

    xmembers('k_xmembers', kinds['player'])
    out.append('#define N_XMEMBERS (int)(sizeof k_xmembers / sizeof *k_xmembers)')
    xmembers('k_xglobals', kinds['names'])
    out.append('#define N_XGLOBALS (int)(sizeof k_xglobals / sizeof *k_xglobals)')
    for k in KINDS:
        kmembers('k_xk_' + k, kinds[k])
    out.append('#define XK_NUMBERED(k) (%s)' % ' || '.join('(k) == XK_%s' % k.upper() for k in KINDS if kinds[k].has('numbered')))
    text = '\n'.join(out) + '\n'
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if old != text:
        open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
        print('lang.h: %d text names; members: %s' % (len(kinds['names'].members),
              ', '.join('%s %d' % (k, len(kinds[k].members)) for k in KINDS)))


if __name__ == '__main__':
    main()
