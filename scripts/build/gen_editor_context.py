"""The editor's view of the one translation unit (run by dll/build.sh): .editor/compile_commands.json.

Only dll/eeaimod.c is compiled; a part (ai/fleet.c) includes nothing and uses what eeaimod.c brought in before it -
windows.h, base/lang.h's internal, game/api/, the earlier parts. An editor that reads the part alone (VS Code's C/C++
extension: .vscode/c_cpp_properties.json points it here) finds none of that. So each part gets the text before its
#include as a forced include (-include .editor/<part>.pre.c): eeaimod.c up to that line, and for a part a part
includes (engine/display.c's present_d3d.c) the includer's lines up to it as well - the editor sees what the
compiler sees there. #line keeps the pasted lines' own file and line (go to definition lands in eeaimod.c).
dinput/eesettings.c is a compile of its own, as build.sh does it. The output is git-ignored (.editor/.gitignore).

    python scripts/build/gen_editor_context.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DLL = os.path.join(ROOT, 'dll')
OUT = os.path.join(ROOT, '.editor')
CC = os.path.join(ROOT, 'local', 'tools', 'llvm-mingw', 'bin', 'i686-w64-mingw32-clang.exe')
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')


def slash(p):
    return os.path.normpath(p).replace('\\', '/')


def lines_of(path):
    with open(path, 'rb') as f:
        return f.read().decode('latin-1').replace('\r\n', '\n').split('\n')


def resolve(name, includer):
    """A quoted include as the compiler finds it: beside the including file, else under dll/ (-I.)."""
    for base in (os.path.dirname(includer), DLL):
        p = os.path.join(base, name)
        if os.path.isfile(p):
            return os.path.normpath(p)
    return None


def walk(path, before, entries):
    """Each quoted include in path gets the text before it: before (the includers' chunks) and path's own lines."""
    lines = lines_of(path)
    for i, line in enumerate(lines):
        m = INCLUDE.match(line)
        target = m and resolve(m.group(1), path)
        if not target or target in entries:
            continue
        chunks = before + [(path, lines[:i])]
        entries[target] = chunks
        walk(target, chunks, entries)


def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, '.gitignore'), 'w', newline='\n') as f:
        f.write('# generated by scripts/build/gen_editor_context.py (dll/build.sh)\n*\n')
    unit = os.path.join(DLL, 'eeaimod.c')
    entries = {}
    walk(unit, [], entries)
    commands = [{'directory': slash(DLL), 'file': slash(unit), 'arguments': [slash(CC), '-I.', '-c', slash(unit)]}]
    dinput = os.path.join(DLL, 'dinput', 'eesettings.c')
    commands.append({'directory': slash(DLL), 'file': slash(dinput), 'arguments': [slash(CC), '-c', slash(dinput)]})
    wanted = set()
    for target, chunks in sorted(entries.items()):
        rel = os.path.relpath(target, DLL)
        pre = os.path.join(OUT, rel.replace(os.sep, '_') + '.pre.c')
        wanted.add(os.path.basename(pre))
        text = ''.join('#line 1 "%s"\n%s\n' % (slash(src), '\n'.join(lines)) for src, lines in chunks)
        old = open(pre, 'rb').read().decode('latin-1') if os.path.isfile(pre) else None
        if text != old:   # unchanged files keep their time: the editor reparses only what moved
            with open(pre, 'wb') as f:
                f.write(text.encode('latin-1'))
        # the includers' folders too: a pasted line's relative include (present_d3d.c) is found as the compiler does
        dirs = []
        for src, _ in chunks:
            d = slash(os.path.dirname(src))
            if d not in dirs:
                dirs.append(d)
        args = [slash(CC), '-I.'] + ['-I' + d for d in dirs] + ['-include', slash(pre), '-c', slash(target)]
        commands.append({'directory': slash(DLL), 'file': slash(target), 'arguments': args})
    for name in os.listdir(OUT):   # a part no longer included loses its context file
        if name.endswith('.pre.c') and name not in wanted:
            os.remove(os.path.join(OUT, name))
    text = json.dumps(commands, indent=1) + '\n'
    path = os.path.join(OUT, 'compile_commands.json')
    if not os.path.isfile(path) or open(path, encoding='utf-8').read() != text:
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)


if __name__ == '__main__':
    main()
