# Build dll/game/api/editor_layout.h from layout_diff.py output: the scenario editor's 1024x768 layout values that
# EE-AOC.exe uses, as patches for both exes (imm32 operands, or float constants to redirect) - Empire Earth.exe's
# operand and AoC's paired one (its last column) -, each with how it follows the screen size, so the mod can compute
# the layout for any resolution in either:
#   value(W, H) = AoC value + fx/2 * (W - 1024) + fy/2 * (H - 768)
# fx/fy (0, 1 or 2 halves) come from the EE -> AoC change: +224 (= 1024 - 800) follows the width (anchored right or
# stretching), +168 (= 768 - 600) the height, half of that = centred. ANCHOR gives them for AoC's redesigns.
# usage: python gen_editor_layout.py local/games/aoc/work/editor_layout3.tsv local/games/aoc/work/editor_layout_pages2.tsv dll/game/api/editor_layout.h
import sys, struct

PUSH_DELTAS = {168, 224, 112, 84}
# constructor 0x58D3E1: minimap rectangle (AoC builds it from constants elsewhere, so the diff can't pair it)
MANUAL = [(0x58D5AC, 662.0, 854.16), (0x58D5B3, 795.0, 1023.0), (0x58D5BA, 454.0, 598.16), (0x58D5C1, 587.0, 767.0)]
# AoC's minimap rectangle (constructor 0x59D615): the screen's width and height (fld [1024.0] / [768.0]) less the
# map's 169.84 and 1 - the two operands redirected, AoC's sites only: (operand, value, fx, fy)
MANUAL_AOC = [(0x59D7CC, 1024.0, 2, 0), (0x59D7DB, 768.0, 0, 2)]

# operands to leave alone although they pass the filter
EXCLUDE = {
    # UIFullBackground("textures\Scenfull", 4, 3, .., 800, 600): not the screen size but the size the tiles cover -
    # the engine scales them by screen / this. EE's tiles are 200 px (AoC's 256 px, hence its 1024x768), so the
    # original values stretch the art to any resolution
    0x58E58C, 0x58E591,
    0x561100, 0x561130, 0x561160,   # EESEInstructions: assert line numbers
    0x5630DC, 0x563148, 0x563176,   # window message ids (WM_USER + n)
    # the player page's diplomacy grid (FUN_0056835a / FUN_005685a3: its buttons' and column numbers' left edge, the
    # row numbers' 137-159): AoC moves them right by 112 and the rule took that for centred, so at 2560 wide the grid
    # stood 770 px off the player names (7-131, never moved). EE's values are the ones that fit: 15 columns of 25 px
    # end at 559, under the 7-561 header and short of the game options at 600 - AoC's 274 run into those
    0x568399, 0x5685F0, 0x568746, 0x56874E,
}
# entries whose EE -> AoC change isn't a plain move: (fx, fy) in halves
ANCHOR = {
    0x58D5AC: (2, 0), 0x58D5B3: (2, 0), 0x58D5BA: (0, 2), 0x58D5C1: (0, 2),   # minimap: bigger in AoC, bottom right
    0x58DA04: (2, 0), 0x58DA0B: (2, 0), 0x58DA12: (0, 2), 0x58DA19: (0, 2),   # hide-UI checkbox, next to the minimap
}

def factors(addr, old, new):
    if addr in ANCHOR:
        return ANCHOR[addr]
    hits = [(fx, fy) for fx in (0, 1, 2) for fy in (0, 1, 2) if abs(fx * 112 + fy * 84 - (new - old)) < 0.6]
    if len(hits) != 1:
        sys.exit('no unique size rule for %06X (%g -> %g): add it to ANCHOR' % (addr, old, new))
    return hits[0]

# our own corrections to AoC's values: operand address -> value
OVERRIDE = {
    # trigger "hide UI" checkbox (19x19, constructor 0x58D3E1): AoC moves it right by 224 like the panels, but the
    # minimap's left edge only moves 192 (662 -> 854), so it ends up half hidden - 19 px left, above the exit button
    0x58DA04: 830.0, 0x58DA0B: 849.0,
}

def u32f(f):
    return struct.unpack('<I', struct.pack('<f', f))[0]

rows, seen = [], set(EXCLUDE)
for line in (l for f in sys.argv[1:-1] for l in open(f)):
    kind, func, name, insn, opaddr, vk, old, new, text, aoc_op = line.rstrip('\n').split('\t')
    old, new, opaddr, aoc_op = float(old), float(new), int(opaddr, 16), int(aoc_op, 16)
    mnem = text.split()[0]
    if opaddr in seen:
        continue
    keep = False
    if kind == 'imm' and vk == 'f' and mnem == 'mov' and max(abs(old), abs(new)) <= 1100:
        keep = True
    elif kind == 'const' and vk == 'f':
        keep = True
    elif kind == 'imm' and vk == 'i' and mnem == 'push' and old >= 250 and round(new - old) in PUSH_DELTAS:
        keep = True   # (assert line numbers moved by 3-4 lines in AoC's sources; the deltas exclude them)
    if keep:
        seen.add(opaddr)
        rows.append((kind, opaddr, aoc_op, vk, old, new, OVERRIDE.get(opaddr, new), name, text))
for addr, old, new in MANUAL:
    if addr not in seen:
        rows.append(('imm', addr, 0, 'f', old, new, new, 'FUN_0058d3e1 (minimap)', 'manual'))

with open(sys.argv[-1], 'w') as out:
    out.write('// Generated by scripts/build/gen_editor_layout.py from scripts/re/layout_diff.py - do not edit.\n'
              '// Scenario editor layout: the values Art of Conquest uses at 1024x768, patched into either exe, and how\n'
              '// each follows the screen size: value = aoc + fx/2 * (W - 1024) + fy/2 * (H - 768).\n'
              '// addr / old per build column (builds.h: the 2017 update, AoC; 0: not in that build): kind 0: imm32 operand\n'
              '// at addr (old = its original value, checked); kind 1: float constant read through the absolute operand at\n'
              '// addr - the operand is redirected to a float of our own. isf: float, else int.\n'
              'internal const struct { uint32_t addr[2]; uint8_t kind, isf; uint32_t old[2]; float aoc; int8_t fx, fy; } k_editor_layout[] = {\n')
    def entry(kind, addr, aoc_op, isf, old, aoc_old, value, fx, fy, note):
        ov = lambda v, a: 0 if not a else u32f(v) if isf else int(v)   # the original value (checked before patching)
        out.write('    { { 0x%06X, 0x%06X }, %d, %d, { 0x%08X, 0x%08X }, %.2ff, %d, %d },   // %s\n'
                  % (addr, aoc_op, 1 if kind == 'const' else 0, int(isf), ov(old, addr), ov(aoc_old, aoc_op), value, fx, fy, note))
    for kind, addr, aoc_op, vk, old, aoc_old, new, name, text in sorted(rows, key=lambda r: r[1]):
        fx, fy = factors(addr, old, new)
        entry(kind, addr, aoc_op, kind == 'const' or vk == 'f', old, aoc_old, new, fx, fy, '%s: %s  %g -> %g' % (name, text, old, new))
    for aoc_op, value, fx, fy in MANUAL_AOC:
        entry('const', 0, aoc_op, True, 0, value, value, fx, fy, 'AoC FUN_0059d615 (minimap): fld dword ptr [%g]' % value)
    out.write('};\n')
print(len(rows) + len(MANUAL_AOC), 'patches written to', sys.argv[-1])
